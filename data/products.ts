function spark(endVal: number, vol = 0.18): number[] {
  const out: number[] = [];
  let v = endVal * (1 - vol);
  for (let i = 0; i < 12; i++) {
    const target = endVal * (1 - vol + vol * (i / 11));
    v =
      v * 0.6 +
      target * 0.4 +
      Math.sin(i * 1.7 + endVal) * vol * endVal * 0.05;
    out.push(Math.round(v * 10) / 10);
  }
  out[11] = endVal;
  return out;
}

